"""EuroPII benchmark: template messages in 12 European languages with EU ID, IBAN, card and IP formats.

Generated by code (python-stdnum checksums), not an NER test. The set's split is kept (``record["part"]``):
``dev`` (415, seed 2027) and ``test`` (2,075, seed 2026). Hard negatives (BAD_IBAN, order numbers...) are
not gold: a prediction on them is a false positive.
"""

import json

from benchmarks.datasets import hf_file, sample_per_lang, valid_spans

NAME = "europii"
HF_ID = "sinceaihq/europii-bench"
REVISION = "b407a9ac7795525035c5c8ca20b73586e64aa571"
LICENCE = "CC-BY-4.0 (cite the card)"
PUBLISH = "scores-only"  # SHORTLIST section 3: no per-example predictions for any round-2 set
SUITE = "pii"


def _records():
    for part in ("dev", "test"):
        with hf_file(HF_ID, f"data/{part}.jsonl", REVISION).open(encoding="utf-8") as source:
            for line in source:
                row = json.loads(line)
                spans = [{"start": s["start"], "end": s["end"], "label": s["label"]} for s in row["spans"]]
                yield {"id": f"{part}:{row['id']}", "lang": row["language"], "text": row["text"], "part": part,
                       "spans": valid_spans(row["text"], spans)}


def load(n: int | None, seed: int) -> list[dict]:
    return sample_per_lang(_records(), n, seed)
